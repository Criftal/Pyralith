export function ClaimCard({ c, compact = false }: { c: Claim; compact?: boolean }) {
  return (
    <article className="rounded-lg border border-line bg-panel p-4">
      <div className="flex flex-wrap items-center gap-1.5">
        <span className="inline-flex items-center rounded border border-line-strong px-1.5 py-0.5 text-[0.7rem] leading-none text-text/85">claim</span>
        <span className="inline-flex items-center rounded border border-line-strong px-1.5 py-0.5 font-mono text-[0.7rem] leading-none text-muted">{c.topic.replace(/_/g, ' ')}</span>
        <span className="ml-auto">
          <VerifiedBadge />
        </span>
      </div>
      {c.label && <div className="mt-2 font-medium text-text">{c.label}</div>}
      <p className="mt-1 text-[0.95rem] leading-snug text-text">
        {tidy(c.text)}
        <AiTag />
      </p>
      {!compact && <blockquote className="mt-3 border-l-2 border-cool/60 pl-3 text-sm leading-relaxed text-muted">“{tidy(c.quote)}”</blockquote>}
      <div className="mt-3 flex flex-wrap items-center gap-3 font-mono text-xs">
        <Cite target={claimTarget(c)} />
        {c.link && (
          <a href={c.link} target="_blank" rel="noreferrer" className="text-cool hover:underline">
            page ↗
          </a>
        )}
      </div>
    </article>
  );
}

/** Scroll to and briefly highlight a record card inside a scope. */
export function useHighlight(scope: string) {
  const [hl, setHl] = useState<string | null>(null);
  const timer = useRef<number | undefined>(undefined);
  const go = useCallback(
    (id: string) => {
      document.getElementById(`${scope}-${id}`)?.scrollIntoView({ behavior: 'smooth', block: 'center' });
      setHl(id);
      window.clearTimeout(timer.current);
      timer.current = window.setTimeout(() => setHl(null), 2600);
    },
    [scope],
  );
  useEffect(() => () => window.clearTimeout(timer.current), []);
  return { hl, go };
}

/** A finding or claim card with its record id, used as a citation target. */
export function RecordCard({
  id,
  scope,
  highlighted,
  rank,
  reason,
  compact = false,
  action,
}: {
  id: string;
  scope: string;
  highlighted: boolean;
  rank?: number;
  reason?: string;
  compact?: boolean;
  action?: ReactNode;
}) {
  const { data } = useData();
  const finding = useMemo(() => data.findings.find((f) => f.id === id), [data.findings, id]);
  const claim = useMemo(() => (finding ? undefined : data.claims.find((c) => c.id === id)), [data.claims, finding, id]);
  if (!finding && !claim) return null;
  return (
    <div id={`${scope}-${id}`} className={`scroll-mt-24 rounded-lg transition-shadow duration-300 ${highlighted ? 'shadow-[0_0_0_2px_var(--color-flame),0_0_24px_rgba(255,107,26,0.35)]' : ''}`}>
      <div className="mb-1 flex flex-wrap items-center gap-x-3 gap-y-1 font-mono text-[0.68rem] text-faint">
        {rank !== undefined && <span className="text-muted">#{rank}</span>}
        <span className="text-cool">{id}</span>
        {reason && <span className="text-muted">{reason}</span>}
        {action && <span className="ml-auto">{action}</span>}
      </div>
      {finding ? <FindingCard f={finding} compact={compact} /> : claim ? <ClaimCard c={claim} compact={compact} /> : null}
    </div>
  );
}

export interface AiState {
  status: 'idle' | 'loading' | 'done' | 'error';
  res?: AskResponse;
  error?: string;
}

export function AiAnswer({ res, onCite }: { res: AskResponse; onCite: (id: string) => void }) {
  const removed = res.stripped > 0 ? ` · ${res.stripped} uncited sentence${res.stripped === 1 ? '' : 's'} removed` : '';
  return (
    <section className="rounded-lg border border-cool/40 bg-cool/[0.05] p-4" aria-live="polite">
      <div className="font-mono text-[0.68rem] uppercase leading-relaxed tracking-[0.14em] text-cool">
        AI-generated by {res.model}; every sentence cites a quote-verified record{removed}
      </div>
      {res.refusal || res.sentences.length === 0 ? (
        <p className="mt-2 text-[0.95rem] text-muted">{res.answer}</p>
      ) : (
        <p className="mt-2 text-[0.95rem] leading-relaxed text-text">
          {res.sentences.map((s, i) => (
            <span key={i} className="mr-1.5">
              {stripCitations(s.text)}
              {s.citations.map((id) => (
                <button
                  key={id}
                  type="button"
                  onClick={() => onCite(id)}
                  title="Scroll to this record"
                  className="ml-1 inline-flex items-center rounded border border-cool/50 px-1 py-0.5 align-middle font-mono text-[0.68rem] leading-none text-cool hover:bg-cool/15"
                >
                  {id}
                </button>
              ))}{' '}
            </span>
          ))}
        </p>
      )}
    </section>
  );
}

export function LiveControls({
  live,
  label,
  state,
  disabled = false,
  onRun,
  offNote,
}: {
  live: LiveStatus | null;
  label: string;
  state: AiState;
  disabled?: boolean;
  onRun: () => void;
  offNote: string;
}) {
  if (live === null) return <p className="font-mono text-xs text-faint">Checking for live AI mode…</p>;
  if (!live.live) return <p className="text-sm text-muted">{offNote}</p>;
  return (
    <div className="flex flex-wrap items-center gap-3">
      <button
        type="button"
        onClick={onRun}
        disabled={disabled || state.status === 'loading'}
        className="rounded-md border border-cool/60 bg-cool/10 px-4 py-2 text-sm font-semibold text-cool transition-colors hover:bg-cool/20 disabled:cursor-not-allowed disabled:opacity-50"
      >
        {state.status === 'loading' ? 'Asking Claude…' : label}
      </button>
      {state.status === 'error' && <p className="text-sm text-flame-soft">{state.error} Showing retrieved evidence only.</p>}
    </div>
  );
}

/** Red team for one finding: deterministic counter-evidence, optionally argued by the live model. */
export function RedTeamPanel({ target, scope, onClose }: { target: Finding; scope: string; onClose: () => void }) {
  const { data } = useData();
  const index = useMemo(() => indexFor(data.findings, data.claims, data.sources), [data.findings, data.claims, data.sources]);
  const items = useMemo(() => counterEvidence(target, data.findings, data.claims, index, 10), [target, data.findings, data.claims, index]);
  const live = useLiveStatus();
  const [ai, setAi] = useState<AiState>({ status: 'idle' });
  const { hl, go } = useHighlight(scope);
  useEffect(() => setAi({ status: 'idle' }), [target.id]);

  const run = async () => {
    setAi({ status: 'loading' });
    try {
      const res = await postAsk({ mode: 'redteam', target: target.id, ids: items.map((i) => i.id) });
      setAi({ status: 'done', res });
    } catch (e) {
      setAi({ status: 'error', error: e instanceof Error ? e.message : 'Live request failed.' });
    }
  };

  return (
    <section aria-label={`Red team for ${target.id}`} className="rounded-xl border border-flame/50 bg-flame/[0.04] p-4">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div className="min-w-0">
          <div className="font-mono text-xs uppercase tracking-[0.2em] text-flame">Red team · {target.id}</div>
          <p className="mt-1 text-sm leading-relaxed text-text/90">Arguing against: “{tidy(target.finding)}”</p>
        </div>
        <button type="button" onClick={onClose} className="rounded border border-line-strong px-2 py-1 font-mono text-xs text-muted hover:text-text">
          close
        </button>
      </div>
      <div className="mt-3">
        <LiveControls
          live={live}
          label="Ask Claude to argue against it (cites only these records)"
          state={ai}
          disabled={items.length === 0}
          onRun={run}
          offNote="Live AI mode is not configured on this deployment. Showing retrieved counter-evidence only."
        />
      </div>
      {ai.status === 'done' && ai.res && (
        <div className="mt-3">
          <AiAnswer res={ai.res} onCite={go} />
        </div>
      )}
      <h4 className="mt-4 font-mono text-[0.68rem] uppercase tracking-[0.18em] text-muted">Counter-evidence retrieved (no AI)</h4>
      {items.length === 0 ? (
        <p className="mt-2 text-sm text-muted">No counter-evidence found in our corpus.</p>
      ) : (
        <ol className="mt-2 space-y-4">
          {items.map((it, i) => (
            <li key={it.id}>
              <RecordCard id={it.id} scope={scope} highlighted={hl === it.id} rank={i + 1} reason={it.reason} compact />
            </li>
          ))}
        </ol>
      )}
    </section>
  );
}
